/**
 * Feature services with working fakes for Settings; every other group stays
 * on the Tauri implementation (which reports "not available" in a browser).
 *
 * @returns Feature services for the harness.
 */
export function fixtureFeatures(): FeatureServices {
  let stored = defaults();
  const wait = <T>(v: T, ms = 120) => new Promise<T>((r) => setTimeout(() => { r(v); }, ms));
  return {
    ...tauriFeatures,
    settings: {
      ...tauriFeatures.settings,
      loadSettings: () => wait(structuredClone(stored)),
      saveSettings: (s) => {
        const issues = validateSettings(s);
        if (issues.length === 0) stored = structuredClone(s);
        return wait({ settings: structuredClone(stored), issues });
      },
      exportSettings: () => wait(JSON.stringify({ format: "strata-settings", version: 1, settings: stored }, null, 2)),
      importSettings: () => wait({ settings: structuredClone(stored), issues: [] }),
      fetchRules: () => wait(rules()),
      reloadRules: () => wait({ builtin: PACKS.reduce((a, [, n]) => a + n, 0), user: 1, problems: [] }),
      openRulesFolder: () => wait(null),
      explainPath: (path) => wait({ ...EXPLANATION, path }, 200),
      fetchHelperService: () => wait({ installed: false, running: false }),
      fetchLicenses: () =>
        wait([
          { name: "tauri", version: "2.11.5", license: "Apache-2.0 OR MIT", ecosystem: "cargo" as const, repository: null },
          { name: "serde", version: "1.0.228", license: "MIT OR Apache-2.0", ecosystem: "cargo" as const, repository: null },
          { name: "rusqlite", version: "0.37.0", license: "MIT", ecosystem: "cargo" as const, repository: null },
          { name: "react", version: "19.3.0", license: "MIT", ecosystem: "npm" as const, repository: null },
          { name: "zustand", version: "5.0.15", license: "MIT", ecosystem: "npm" as const, repository: null },
        ]),
      checkForUpdates: () => wait({ current: "0.1.0", latest: null, available: false, channel: stored.updates.channel }, 400),
      clearData: () => wait(null),
    },
  };
}
