const PACKS: readonly [string, number][] = [
  ["windows", 64],
  ["browsers", 38],
  ["dev-tools", 52],
  ["games", 21],
  ["ai-models", 12],
  ["media-apps", 17],
];

function rules(): RuleInfo[] {
  const out: RuleInfo[] = [];
  for (const [pack, n] of PACKS) {
    for (let i = 0; i < n; i++) {
      out.push({
        id: `${pack}.rule-${i}`,
        name: `${pack} rule ${i}`,
        pack,
        source: "builtin",
        category: 6,
        safety: "safe",
        explain: "Regenerated by the app.",
        action: "delete",
        app: null,
        regenerable: true,
        overriddenBy: pack === "dev-tools" && i < 2 ? `mine.override-${i}` : null,
      });
    }
  }
  out.push({ id: "mine.override-0", name: "Keep build cache", pack: "my-rules", source: "user", category: 5, safety: "careful", explain: "Shared build cache.", action: "info_only", app: null, regenerable: false, overriddenBy: null });
  return out;
}

