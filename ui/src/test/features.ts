/**
 * Test doubles for the wave-2 feature services: every call rejects with
 * BackendUnavailableError unless a test overrides it, plus small synthetic
 * fixtures (placeholder paths only).
 */
import { vi } from "vitest";
import type { FeatureServices } from "../features";
import { BackendUnavailableError } from "../lib/backend";
import type { CleanupPlan, QueueEntry } from "../lib/cleanup";
import type { DupeGroup } from "../lib/dupes";
import type { Settings } from "../lib/settings";

type Api = Record<string, (...args: never[]) => unknown>;

function unavailable(group: string): Api {
  return new Proxy(
    {},
    {
      get(_t, name: string) {
        if (name.startsWith("watch")) return () => () => undefined;
        return () => Promise.reject(new BackendUnavailableError(`${group}.${name}`, "not in this test"));
      },
    },
  );
}

/** Partial overrides per API group. */
export type FeatureOverrides = { [K in keyof FeatureServices]?: Partial<FeatureServices[K]> };

/**
 * Builds feature services where only the overridden calls work.
 *
 * @param overrides - Per-group implementations.
 * @returns Feature services.
 */
export function fakeFeatures(overrides: FeatureOverrides = {}): FeatureServices {
  const groups = ["cleanup", "tools", "insights", "dupes", "activity", "history", "settings"] as const;
  const out = {} as Record<string, unknown>;
  for (const g of groups) {
    const base = unavailable(g);
    const o = (overrides[g] ?? {}) as Api;
    out[g] = new Proxy(o, {
      get(t, name: string) {
        return name in t ? t[name] : base[name];
      },
    });
  }
  return out as unknown as FeatureServices;
}

