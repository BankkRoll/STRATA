/** A plan over the given entries with no warnings. */
export function plan(items: QueueEntry[], patch: Partial<CleanupPlan> = {}): CleanupPlan {
  return {
    planId: 7,
    items,
    totals: [],
    volumes: [{ mountPoint: "C:\\", recycleBin: { state: "available", capacity: 50 * 1024 ** 3, used: 0 }, items: items.length, bytes: items.reduce((a, i) => a + i.bytes, 0) }],
    warnings: [],
    largeDeleteBytes: 10 * 1024 ** 3,
    defaultMethod: "recycle_bin",
    ...patch,
  };
}

/** A duplicate group of `n` copies; copy 0 is the suggested keep. */
export function dupeGroup(id: number, n: number): DupeGroup {
  return {
    id,
    size: 50 * 1024 ** 2,
    wastedBytes: 50 * 1024 ** 2 * (n - 1),
    sameVolume: true,
    keep: { fileId: 0, reason: "oldest", explain: "Oldest copy." },
    files: Array.from({ length: n }, (_, i) => ({
      fileId: i,
      volumeId: "fixture",
      entryId: 1000 + id * 10 + i,
      path: `D:\\Media\\copy-${id}-${i}.mkv`,
      modifiedMs: Date.UTC(2025, 0, 1 + i),
      safety: null,
      inDownloads: i === n - 1,
    })),
  };
}

